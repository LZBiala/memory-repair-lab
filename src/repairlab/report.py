"""Single source of truth for every published number: the generations SVG and
the README AUTOGEN block, rendered from metrics.jsonl. CI regenerates and
`git diff --exit-code` fails the build on any drift.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

AUTOGEN_BEGIN = "<!-- AUTOGEN:BEGIN — rendered by report.py from metrics.jsonl; do not edit by hand -->"
AUTOGEN_END = "<!-- AUTOGEN:END -->"
DISCLAIMER = "scripted repairer — proves the loop and the failure signal, never model capability"

_COLORS = {"gen0-frozen": "#6b7280", "repair": "#0f766e", "placebo": "#b45309", "goodhart-bloat": "#b91c1c"}


@dataclass(frozen=True)
class Metrics:
    rows: list[dict[str, object]]
    summary: dict[str, object]


def load_metrics(path: Path) -> Metrics:
    rows: list[dict[str, object]] = []
    summary: dict[str, object] = {}
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            row = json.loads(line)
            if row["kind"] == "summary":
                summary = row
            else:
                rows.append(row)
    return Metrics(rows=rows, summary=summary)


def _arm(metrics: Metrics, arm: str, split: str) -> dict[str, object]:
    return next(
        r for r in metrics.rows if r["arm"] == arm and r["split"] == split
    )


def render_generations_svg(metrics: Metrics) -> str:
    """Held-out recall per arm (bars) with each arm's index token cost printed
    under it — the Goodhart arm's gain and its price share one frame."""
    arms = ["gen0-frozen", "repair", "placebo", "goodhart-bloat"]
    width, height = 760, 320
    left, right, top, bottom = 70, 30, 56, 96
    plot_w, plot_h = width - left - right, height - top - bottom
    bar_w = 90

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="monospace" font-size="12">',
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
        f'<text x="{left}" y="22" font-size="14" fill="#111111">'
        "held-out recall per arm — with each arm's index cost printed beneath</text>",
    ]
    total = int(_arm(metrics, "gen0-frozen", "held_out")["total"])  # type: ignore[arg-type]
    for i, arm in enumerate(arms):
        row = _arm(metrics, arm, "held_out")
        hits = int(row["hits"])  # type: ignore[arg-type]
        tokens = int(row["index_tokens"])  # type: ignore[arg-type]
        frac = hits / total if total else 0.0
        x = left + i * (plot_w // len(arms)) + 20
        bar_h = plot_h * frac
        parts.append(
            f'<rect x="{x}" y="{top + plot_h - bar_h:.1f}" width="{bar_w}" '
            f'height="{bar_h:.1f}" fill="{_COLORS[arm]}" opacity="0.9"/>'
        )
        parts.append(
            f'<text x="{x + bar_w / 2:.0f}" y="{top + plot_h - bar_h - 8:.1f}" '
            f'text-anchor="middle" fill="#111111" font-weight="bold">{hits}/{total}</text>'
        )
        parts.append(
            f'<text x="{x + bar_w / 2:.0f}" y="{top + plot_h + 18}" text-anchor="middle" '
            f'fill="#374151">{arm}</text>'
        )
        parts.append(
            f'<text x="{x + bar_w / 2:.0f}" y="{top + plot_h + 34}" text-anchor="middle" '
            f'fill="#6b7280">index {tokens} tok</text>'
        )
    parts.append(
        f'<text x="{left}" y="{height - 20}" fill="#991b1b">{DISCLAIMER}</text>'
    )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def render_claims(metrics: Metrics) -> str:
    s = metrics.summary
    gen0 = _arm(metrics, "gen0-frozen", "held_out")
    mend = _arm(metrics, "repair", "held_out")
    pla = _arm(metrics, "placebo", "held_out")
    blo = _arm(metrics, "goodhart-bloat", "held_out")
    lines = [
        "| claim | number (regenerated by CI) | how measured | honest caveat |",
        "|---|---|---|---|",
        (
            "| Cited repairs improve HELD-OUT recall "
            f"| **{gen0['hits']}/{gen0['total']} → {mend['hits']}/{mend['total']} "
            "held-out hits after one repair generation** | held-out phrasings sealed "
            "before generation zero; a test asserts they never enter repairer input; "
            "frozen gen-0 replayed in the same run | scripted repairer on "
            "author-labeled fixtures — proves the loop, an upper bound by "
            "construction, never model capability |"
        ),
        (
            "| The failure signal — not editing — does the work "
            f"| **placebo arm (same edit budget, blind): {pla['hits']}/{pla['total']} "
            "— unchanged from gen-0** | identical budget; placebo edits computed "
            "without reading failure records | one corpus, one deterministic churn "
            "rule; the arm separates signal from motion, nothing more |"
        ),
        (
            "| Every accepted edit cites its failure record "
            f"| **{s['accepted']} accepted edits, {s['citation_coverage']} cited; "
            f"{s['reverted']} reverted by the regression gate** | the protocol "
            "refuses uncited edits; the full suite replays after every acceptance | "
            "conformance of the loop, labeled as such |"
        ),
        (
            "| Gaming recall has a visible price (the Goodhart demo) "
            f"| **hook-bloat arm: {blo['hits']}/{blo['total']} held-out hits at "
            f"index cost {blo['index_tokens']} tok vs repair arm {mend['hits']}/"
            f"{mend['total']} at {mend['index_tokens']} tok** | an authored strategy "
            "committed and measured beside the honest one | a demonstration of a "
            "failure mode, not evidence any real improver behaves this way |"
        ),
        (
            f"| The loop terminates | **stop rule fired: {s['stop_reason']}** | the "
            "generation loop halts in CI and prints its reason in the ledger | "
            "plateau on this corpus says nothing about any other corpus |"
        ),
    ]
    return "\n".join(lines)


def inject_readme(readme_path: Path, block: str) -> None:
    text = readme_path.read_text(encoding="utf-8")
    begin = text.index(AUTOGEN_BEGIN)
    end = text.index(AUTOGEN_END) + len(AUTOGEN_END)
    new = text[:begin] + AUTOGEN_BEGIN + "\n\n" + block + "\n\n" + AUTOGEN_END + text[end:]
    with readme_path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
